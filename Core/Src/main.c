/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
	void usart2_send_string(const char *str)
	{
		while(*str)
		{
			while(!LL_USART_IsActiveFlag_TXE(USART2));
			LL_USART_TransmitData8(USART2, *str++);
		}
	}
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  LL_APB2_GRP1_EnableClock(LL_APB2_GRP1_PERIPH_SYSCFG);
  LL_APB1_GRP1_EnableClock(LL_APB1_GRP1_PERIPH_PWR);

  /* System interrupt init*/
  NVIC_SetPriorityGrouping(NVIC_PRIORITYGROUP_4);

  /* SysTick_IRQn interrupt configuration */
  NVIC_SetPriority(SysTick_IRQn, NVIC_EncodePriority(NVIC_GetPriorityGrouping(),15, 0));

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  uint8_t hts_ok = hts221_init(i2c_master_read, i2c_master_write);
  // LPS22HB -> 0xB1
  uint8_t lps_ok = lps22hb_init(i2c_master_read, i2c_master_write);
  float p0 = lps22hb_get_pressure();
  LL_mDelay(200);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  usart2_send_string("hello VRS :)\r\n");
	  float t   = hts221_get_temperature();
	  float h   = hts221_get_humidity();
	  float p   = lps22hb_get_pressure();
	  float alt = lps22hb_get_altitude(p, p0);

	  char buf[64];
	  sprintf(buf, "%04.1f,%02d,%07.2f,%05.2f\r\n", t, (int)(h + 0.5f), p, alt);
	  usart2_send_string(buf);

	  LL_mDelay(200);
    /* USER CODE END WHILE */


    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

